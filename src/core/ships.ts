export type ShipKey = 'classic' | 'fighter' | 'falcon' | 'xwing'

export type TintName = 'hull' | 'accent' | 'engine' | 'cockpit'

export type ShipLayer = { pattern: number[][]; tint: TintName }

export type ShipDef = {
  key: ShipKey
  name: string
  description: string
  layers: ShipLayer[]
  /**
   * Visual draw size for SVG renderer (decoupled from hitbox).
   * Hitbox stays at playerWidth × playerHeight from gameMeta;
   * the SVG sprite is drawn at this size to preserve its aspect ratio.
   * When SVG sprites are disabled, the renderer falls back to hitbox dims.
   */
  visualWidth: number
  visualHeight: number
}

